const dictionaries: Record<"es" | "en", Dict> = { es, en };

function lookup(dict: Dict, path: string[]): string | undefined {
  let current: string | Dict = dict;
  for (const segment of path) {
    if (typeof current !== "object" || current === null) return undefined;
    const next: string | Dict | undefined = current[segment];
    if (next === undefined) return undefined;
    current = next;
  }
  return typeof current === "string" ? current : undefined;
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) => (key in vars ? String(vars[key]) : match));
}

export function translate(locale: "es" | "en", key: string, vars?: Record<string, string | number>): string {
  const path = key.split(".");
  const value = lookup(dictionaries[locale], path) ?? lookup(dictionaries.es, path) ?? key;
  return interpolate(value, vars);
}

export function useT() {
  const locale = useLocaleStore((state) => state.locale);
  return (key: string, vars?: Record<string, string | number>) => translate(locale, key, vars);
}

export function useLocale() {
  return useLocaleStore((state) => state.locale);
}
